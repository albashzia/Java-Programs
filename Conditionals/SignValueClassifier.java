package Conditionals;
public class SignValueClassifier
{
    public static void main(String[] args) 
    {
        int x = 10;
        if(x > 0)
        {
            System.out.println("1");
        }
        else if(x < 0)
        {
            System.out.println("-1");
        }
            else if(x == 0)
        {
            System.out.println("0");
        }
    }
}
